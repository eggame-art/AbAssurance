
SET NOCOUNT ON;

IF SUSER_SNAME() <> N'abassurance_reader'
    OR IS_SRVROLEMEMBER('sysadmin') <> 0
BEGIN
    THROW 51000, 'Unexpected SQL identity or administrator rights.', 1;
END;

SELECT TOP (1) AP_USER_ID FROM dbo.AP_USERS;
SELECT TOP (1) AP_CONTRACT_REF FROM dbo.AP_CONTRACTS;
SELECT TOP (1) AP_SINISTRE_NUM FROM dbo.AP_CLAIMS;
SELECT TOP (1) AP_PAYMENT_REF FROM dbo.AP_PAYMENTS;

BEGIN TRY
    EXEC(N'DELETE FROM dbo.AP_USERS WHERE 1 = 0');

    THROW 51000, 'DELETE unexpectedly allowed.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 229 THROW;
END CATCH;

BEGIN TRY
    EXEC(N'UPDATE dbo.AP_USERS SET AP_FULL_NAME = AP_FULL_NAME WHERE 1 = 0');

    THROW 51000, 'UPDATE unexpectedly allowed.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 229 THROW;
END CATCH;

BEGIN TRY
    EXEC(N'INSERT INTO dbo.AP_USERS (AP_USER_ID) SELECT -2147483648 WHERE 1 = 0');

    THROW 51000, 'INSERT unexpectedly allowed.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 229 THROW;
END CATCH;

BEGIN TRY
    BEGIN TRANSACTION;

    EXEC(N'CREATE TABLE dbo.__security_probe (id INT)');

    ROLLBACK TRANSACTION;

    THROW 51000, 'CREATE TABLE unexpectedly allowed.', 1;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    IF ERROR_NUMBER() NOT IN (229, 262, 2760) THROW;
END CATCH;

PRINT 'Service account: SELECT works; INSERT, UPDATE, DELETE and CREATE TABLE are blocked.';
