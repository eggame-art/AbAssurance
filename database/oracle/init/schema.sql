WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = ABASSURANCE;

DECLARE
    PROCEDURE create_if_missing(ddl VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE ddl;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -955 THEN
                RAISE;
            END IF;
    END;
BEGIN
    create_if_missing(q'[
CREATE TABLE AB_CLIENT (
    AB_CLIENT_ID       NUMBER CONSTRAINT PK_AB_CLIENT PRIMARY KEY,
    AB_NOM             VARCHAR2(100),
    AB_PRENOM          VARCHAR2(100),
    AB_DATE_NAISSANCE  DATE,
    AB_EMAIL           VARCHAR2(150),
    AB_TELEPHONE       VARCHAR2(20),
    AB_ADRESSE         VARCHAR2(255),
    AB_CODE_POSTAL     VARCHAR2(10),
    AB_NUM_FISCAL      VARCHAR2(30),
    AB_DATE_CREATION   TIMESTAMP,
    AB_STATUT_CLIENT   VARCHAR2(20)
)
]');

    create_if_missing(q'[
CREATE TABLE AB_CONTRAT (
    AB_POLICY_NUMBER   VARCHAR2(30) CONSTRAINT PK_AB_CONTRAT PRIMARY KEY,
    AB_CLIENT_ID       NUMBER NOT NULL,
    AB_TYPE_ASSURANCE  VARCHAR2(50),
    AB_DATE_DEBUT      DATE,
    AB_DATE_FIN        DATE,
    AB_PRIME_ANNUELLE  NUMBER(10,2),
    AB_STATUT_CONTRAT  VARCHAR2(20),
    AB_AGENCE_ID       NUMBER,
    CONSTRAINT FK_AB_CONTRAT_CLIENT FOREIGN KEY (AB_CLIENT_ID)
        REFERENCES AB_CLIENT (AB_CLIENT_ID)
)
]');

    create_if_missing(q'[
CREATE TABLE AB_SINISTRE (
    AB_CLAIM_ID        NUMBER CONSTRAINT PK_AB_SINISTRE PRIMARY KEY,
    AB_POLICY_NUMBER   VARCHAR2(30) NOT NULL,
    AB_DATE_SINISTRE   TIMESTAMP,
    AB_MONTANT_ESTIME  NUMBER(12,2),
    AB_STATUT_SINISTRE VARCHAR2(30),
    AB_DESCRIPTION     CLOB,
    CONSTRAINT FK_AB_SINISTRE_CONTRAT FOREIGN KEY (AB_POLICY_NUMBER)
        REFERENCES AB_CONTRAT (AB_POLICY_NUMBER)
)
]');

    create_if_missing(q'[
CREATE TABLE AB_PAIEMENT (
    AB_PAYMENT_ID      NUMBER CONSTRAINT PK_AB_PAIEMENT PRIMARY KEY,
    AB_POLICY_NUMBER   VARCHAR2(30) NOT NULL,
    AB_DATE_PAIEMENT   DATE,
    AB_MONTANT         NUMBER(10,2),
    AB_MODE_PAIEMENT   VARCHAR2(30),
    CONSTRAINT FK_AB_PAIEMENT_CONTRAT FOREIGN KEY (AB_POLICY_NUMBER)
        REFERENCES AB_CONTRAT (AB_POLICY_NUMBER)
)
]');

    create_if_missing(q'[
CREATE INDEX IX_AB_CONTRAT_CLIENT ON AB_CONTRAT (AB_CLIENT_ID)
]');

    create_if_missing(q'[
CREATE INDEX IX_AB_SINISTRE_CONTRAT ON AB_SINISTRE (AB_POLICY_NUMBER)
]');

    create_if_missing(q'[
CREATE INDEX IX_AB_PAIEMENT_CONTRAT ON AB_PAIEMENT (AB_POLICY_NUMBER)
]');
END;
/
