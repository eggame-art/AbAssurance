SET NOCOUNT ON;
IF DB_ID(N'AssurePlus') IS NULL
    EXEC(N'CREATE DATABASE [AssurePlus]');
GO

USE [AssurePlus];
GO
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.AP_USERS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AP_USERS (
        AP_USER_ID         INT NOT NULL CONSTRAINT PK_AP_USERS PRIMARY KEY,
        AP_FULL_NAME       NVARCHAR(200) NULL,
        AP_BIRTH_DATE      VARCHAR(10) NULL,
        AP_MAIL_ADDRESS    NVARCHAR(150) NULL,
        AP_PHONE_NUMBER    NVARCHAR(25) NULL,
        AP_STREET_ADDRESS  NVARCHAR(255) NULL,
        AP_ZIP_CODE        NVARCHAR(10) NULL,
        AP_CREATED_AT      DATETIME NULL,
        AP_CUSTOMER_STATUS NVARCHAR(20) NULL,
        AP_LOYALTY_SCORE   INT NULL
    );
END;

IF OBJECT_ID(N'dbo.AP_CONTRACTS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AP_CONTRACTS (
        AP_CONTRACT_REF    NVARCHAR(30) NOT NULL CONSTRAINT PK_AP_CONTRACTS PRIMARY KEY,
        AP_USER_ID         INT NOT NULL,
        AP_PRODUCT_CODE    NVARCHAR(50) NULL,
        AP_START_DATE      DATETIME NULL,
        AP_END_DATE        DATETIME NULL,
        AP_MONTHLY_PREMIUM DECIMAL(10,2) NULL,
        AP_CONTRACT_STATE  NVARCHAR(20) NULL,
        AP_BROKER_CODE     NVARCHAR(30) NULL,
        CONSTRAINT FK_AP_CONTRACTS_USER FOREIGN KEY (AP_USER_ID)
            REFERENCES dbo.AP_USERS (AP_USER_ID)
    );
    CREATE INDEX IX_AP_CONTRACTS_USER ON dbo.AP_CONTRACTS (AP_USER_ID);
END;

IF OBJECT_ID(N'dbo.AP_CLAIMS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AP_CLAIMS (
        AP_SINISTRE_NUM     INT NOT NULL CONSTRAINT PK_AP_CLAIMS PRIMARY KEY,
        AP_CONTRACT_REF     NVARCHAR(30) NOT NULL,
        AP_INCIDENT_DATE    VARCHAR(19) NULL,
        AP_ESTIMATED_AMOUNT DECIMAL(12,2) NULL,
        AP_CLAIM_STATUS     NVARCHAR(30) NULL,
        AP_CLAIM_COMMENT    NVARCHAR(MAX) NULL,
        AP_FRAUD_SCORE      DECIMAL(5,2) NULL,
        CONSTRAINT FK_AP_CLAIMS_CONTRACT FOREIGN KEY (AP_CONTRACT_REF)
            REFERENCES dbo.AP_CONTRACTS (AP_CONTRACT_REF)
    );
    CREATE INDEX IX_AP_CLAIMS_CONTRACT ON dbo.AP_CLAIMS (AP_CONTRACT_REF);
END;

IF OBJECT_ID(N'dbo.AP_PAYMENTS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AP_PAYMENTS (
        AP_PAYMENT_REF        UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_AP_PAYMENTS PRIMARY KEY,
        AP_CONTRACT_REF       NVARCHAR(30) NOT NULL,
        AP_PAYMENT_DATETIME   DATETIME NULL,
        AP_AMOUNT_PAID        DECIMAL(10,2) NULL,
        AP_PAYMENT_CHANNEL    NVARCHAR(30) NULL,
        AP_TRANSACTION_STATUS NVARCHAR(20) NULL,
        CONSTRAINT FK_AP_PAYMENTS_CONTRACT FOREIGN KEY (AP_CONTRACT_REF)
            REFERENCES dbo.AP_CONTRACTS (AP_CONTRACT_REF)
    );
    CREATE INDEX IX_AP_PAYMENTS_CONTRACT ON dbo.AP_PAYMENTS (AP_CONTRACT_REF);
END;

COMMIT TRANSACTION;
GO
